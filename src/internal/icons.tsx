/**
 * Glyphs for the 59 icon names in the A2UI basic catalog.
 *
 * Path data is taken from Google's Material Symbols (Outlined, 24px, weight
 * 400), Apache License 2.0, https://github.com/google/material-design-icons.
 * Embedding the glyphs keeps the package free of a font dependency: the
 * catalog renders the same icon whether or not the host loads the Material
 * Symbols font. Each glyph is a source component for the base library's
 * `Icon`, so it forwards the class and accessibility attributes it is given.
 */
function glyph(d: string): IconSource {
  const Glyph = (props: IconSourceProps) => (
    <svg viewBox="0 -960 960 960" {...props}>
      <path d={d} />
    </svg>
  )
  return Glyph
}

