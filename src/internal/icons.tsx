/** `priority_high` and `priority-high` become `priorityHigh`; camelCase passes through. */
export function toCatalogIconName(name: string): string {
  if (!/[_-]/.test(name)) return name
  return name.toLowerCase().replace(/[_-]+([a-z0-9])/g, (_, letter: string) => letter.toUpperCase())
}

/** The embedded glyph for a catalog or Material Symbols name, if there is one. */
export function resolveIconGlyph(name: string): IconSource | undefined {
  const key = toCatalogIconName(name)
  return isA2uiIconName(key) ? ICON_GLYPHS[key] : EXTRA_ICON_GLYPHS[key]
}
